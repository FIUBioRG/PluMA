static bool venvActivated = false;

Py::Py(
    std::string language,
    std::string ext,
    std::string p
) : Language(language, ext, p) {}

#if defined(_WIN32) && defined(HAVE_PYTHON)
// pluma.exe links pythonXY.dll with /DELAYLOAD (see SConscript.windows) so it
// starts on machines/shells where that DLL is not on PATH; Python is only
// needed once a Python plugin runs.  Find and load the DLL by full path first;
// the delay-load helper then binds to the already-loaded module.

// "3.15" or "3.15t" (free-threaded): the PEP 514 tag; the DLL name drops the dot.
static std::string pythonTag() {
    std::string tag = std::to_string(PY_MAJOR_VERSION) + "." + std::to_string(PY_MINOR_VERSION);
#ifdef Py_GIL_DISABLED
    tag += "t";
#endif
    return tag;
}

// PEP 514 registry tag: the python.org installer registers 32-bit and ARM64
// installs as "X.Y-32" / "X.Y-arm64" (x64 has no suffix).
static std::string pythonRegistryTag() {
    std::string tag = pythonTag();
#if defined(_M_ARM64)
    tag += "-arm64";
#elif defined(_M_IX86)
    tag += "-32";
#endif
    return tag;
}

static std::string pythonDllName() {
    std::string tag = pythonTag();
    tag.erase(tag.find('.'), 1);
    return "python" + tag + ".dll";
}

// pythonXY.dll candidates: the absolute PATH entries first (so the user's
// PATH choice wins), then the PEP 514 registration written by the python.org
// installer, then the Python SCons compiled against.
static bool preloadPython() {
    const std::string key = "SOFTWARE\\Python\\PythonCore\\" + pythonRegistryTag() + "\\InstallPath";
    std::vector<std::string> dirs = pluma::absolutePathDirs();
    dirs.push_back(pluma::registryString(HKEY_CURRENT_USER, key, NULL));
    dirs.push_back(pluma::registryString(HKEY_LOCAL_MACHINE, key, NULL));
#ifdef PLUMA_BUILD_PYTHON_DIR
    // The installation SCons compiled against (covers installs without a
    // PEP 514 registration: uv, conda, pyenv-win, embeddable zip, ...).
    dirs.push_back(PLUMA_BUILD_PYTHON_DIR);
#endif
    return pluma::preloadDll(pythonDllName(), dirs);
}
#endif

#ifdef HAVE_PYTHON
static void activateVenv(const std::string& cwd) {
    if (venvActivated) return;
    venvActivated = true;

    std::string venvPath = cwd + "/.venv";
    if (!pluma::isDirectory(venvPath))
        return;

    // POSIX venvs keep packages in lib/pythonX.Y/site-packages, Windows venvs
    // in Lib/site-packages.
    std::string script =
        "import sys, os\n"
        "venv = os.path.join('" + cwd + "', '.venv')\n"
        "version = f'python{sys.version_info.major}.{sys.version_info.minor}'\n"
        "site_pkgs = os.path.join(venv, 'Lib', 'site-packages') if os.name == 'nt' else "
        "os.path.join(venv, 'lib', version, 'site-packages')\n"
        "if os.path.isdir(site_pkgs):\n"
        "    import site\n"
        "    site.addsitedir(site_pkgs)\n";
    PyRun_SimpleString(script.c_str());
}
#endif

void Py::executePlugin(
    std::string pluginname,
    std::string inputname,
    std::string outputname
) {
    // Not in the plugin path: fails before any plugin code.
    findPluginFile(pluginname);
#ifdef HAVE_PYTHON
#ifdef _WIN32
    static const bool pythonFound = preloadPython();
    if (!pythonFound) {
        PluginManager::getInstance().log("Python (" + pythonDllName() + ") was not found; cannot run " + pluginname + ".");
        throw PluginNotStarted("Python runtime not found");
    }
#endif
    // Forward slashes: the paths go into Python string literals below.
    std::string cwd = pluma::normalizeSlashes(pluma::currentDirectory());
    if (!Py_IsInitialized()) {
        Py_Initialize();
#ifdef _WIN32
        // An embedded interpreter reports the host executable (pluma.exe) as
        // sys.executable, so multiprocessing's spawn -- the only start method
        // on Windows -- and subprocess.run([sys.executable, ...]) would
        // relaunch PluMA.  Point them at the installation's python.exe.
        PyRun_SimpleString(
            "import os as _os, sys as _sys\n"
            "_exe = _os.path.join(_sys.base_exec_prefix, 'python.exe')\n"
            "if _os.path.isfile(_exe):\n"
            "    _sys.executable = _sys._base_executable = _exe\n"
            "del _os, _sys, _exe\n");
#endif
    }

    PyRun_SimpleString("import sys");
    PyRun_SimpleString(("sys.path.append(\""+cwd+"/\")").c_str());

    activateVenv(cwd);

    std::vector<std::string> roots = pluma::splitPathList(pluginpath);
    for (size_t i = 0; i < roots.size(); ++i) {
        const std::string path = pluma::normalizeSlashes(roots[i]);
        PyRun_SimpleString(("sys.path.append(\""+path+pluginname+"/\")").c_str());
        PyRun_SimpleString(("sys.path.append(\""+path+"/\")").c_str());
    }

    inputname = pluma::normalizeSlashes(inputname);
    outputname = pluma::normalizeSlashes(outputname);
    // PyRun_SimpleString returns -1 when the code raised (the traceback is
    // printed).  Import or construction failing: the plugin never reached
    // input(), so the step counts as not started (an existing output is kept).
    if (PyRun_SimpleString(("import "+pluginname+"Plugin").c_str()) != 0 ||
        PyRun_SimpleString(("plugin = "+pluginname+"Plugin."+pluginname+"Plugin()").c_str()) != 0) {
        PluginManager::getInstance().log("Python Plugin "+pluginname+" failed to load.");
        throw PluginNotStarted("Python plugin " + pluginname + " failed to load");
    }
    PluginManager::getInstance().log("Executing input() For Python Plugin "+pluginname);
    if (PyRun_SimpleString(("plugin.input(\""+inputname+"\")").c_str()) != 0) {
        // An unmet dependency() in input(): not started, as in every language.
        if (PluginManager::takeDependencyFailed()) {
            PluginManager::getInstance().log("Python Plugin "+pluginname+": dependency not met in input().");
            throw PluginNotStarted("Python plugin " + pluginname + ": dependency not met");
        }
        PluginManager::getInstance().log("Python Plugin "+pluginname+" failed in input().");
        throw std::runtime_error("Python plugin " + pluginname + " failed in input()");
    }
    PluginManager::getInstance().log("Executing run() For Python Plugin "+pluginname);
    if (PyRun_SimpleString("plugin.run()") != 0) {
        PluginManager::getInstance().log("Python Plugin "+pluginname+" failed in run().");
        throw std::runtime_error("Python plugin " + pluginname + " failed in run()");
    }
    PluginManager::getInstance().log("Executing output() For Python Plugin "+pluginname);
    if (PyRun_SimpleString(("plugin.output(\""+outputname+"\")").c_str()) != 0) {
        PluginManager::getInstance().log("Python Plugin "+pluginname+" failed in output().");
        throw std::runtime_error("Python plugin " + pluginname + " failed in output()");
    }
    PluginManager::getInstance().log("Python Plugin "+pluginname+" completed successfully.");
#else
    notEnabled(pluginname);
#endif
}

void Py::unload() {
#ifdef HAVE_PYTHON
#ifdef _WIN32
    // Never started (Python not installed, or no Python plugin ran): calling
    // into the delay-loaded DLL would load it now, or fail.
    if (!GetModuleHandleA(pythonDllName().c_str())) return;
#endif
    if (Py_IsInitialized()) Py_Finalize();
#endif
}
