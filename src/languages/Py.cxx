// Paths are handed to Python as objects (decoded with the filesystem
// encoding), never pasted into Python source, so quotes, backslashes and
// non-ASCII characters in paths are safe.
static PyObject* pyPath(const std::string& path) {
    return PyUnicode_DecodeFSDefault(path.c_str());
}

// Exit status carried by a SystemExit instance: None -> 0, int -> that
// value, anything else (e.g. a message string) -> 1, like the interpreter.
static long systemExitCode(PyObject* exc) {
    PyObject* code = PyObject_GetAttrString(exc, "code");
    if (!code) { PyErr_Clear(); return 1; }
    long status = 1;
    // Not `code == Py_None`: Py_None is a data import, which cannot come
    // from the delay-loaded pythonXY.dll on Windows.  None is obtained
    // through a function instead (Py_BuildValue("") returns it), on every
    // Python version.
    PyObject* none = Py_BuildValue("");
    const bool isNone = code == none;
    Py_XDECREF(none);
    if (isNone) status = 0;
    else if (PyLong_Check(code)) status = PyLong_AsLong(code);
    else {
        // sys.exit("message"): Python prints the message to stderr; so do we
        // (and log it), so the reason for the failure is not lost.
        PyObject* text = PyObject_Str(code);
        const char* utf8 = text ? PyUnicode_AsUTF8(text) : NULL;
        if (utf8) {
            std::cerr << utf8 << std::endl;
            PluginManager::getInstance().log(std::string("sys.exit message: ") + utf8);
        }
        Py_XDECREF(text);
    }
    if (PyErr_Occurred()) { PyErr_Clear(); status = 1; }
    Py_DECREF(code);
    return status;
}

// Prints and clears the pending Python exception.  Returns true only for
// sys.exit() / sys.exit(0), which ends the plugin successfully.  SystemExit is
// never passed to PyErr_Print, which would exit the whole process from this
// (possibly kitty) thread, bypassing PluMA's orderly pipeline stop.
static bool reportPythonError(const std::string& pluginname) {
#if PY_VERSION_HEX >= 0x030C0000
    PyObject* exc = PyErr_GetRaisedException();
#else
    PyObject *type, *value, *tb;
    PyErr_Fetch(&type, &value, &tb);
    PyErr_NormalizeException(&type, &value, &tb);
    if (tb && value) PyException_SetTraceback(value, tb);
    Py_XDECREF(type);
    Py_XDECREF(tb);
    PyObject* exc = value;
#endif
    if (!exc) return false;
    bool cleanExit = false;
    PyObject* builtins = PyImport_ImportModule("builtins");
    PyObject* systemExit = builtins ? PyObject_GetAttrString(builtins, "SystemExit") : NULL;
    if (!systemExit) PyErr_Clear();
    if (systemExit && PyErr_GivenExceptionMatches(exc, systemExit)) {
        const long status = systemExitCode(exc);
        cleanExit = (status == 0);
        PluginManager::getInstance().log("Python Plugin " + pluginname + " called sys.exit(" +
                                         std::to_string(status) + ").");
        if (!cleanExit)
            std::cerr << "[PluMA] Python plugin " << pluginname << " called sys.exit(" << status << ")" << std::endl;
        Py_DECREF(exc);
    } else {
#if PY_VERSION_HEX >= 0x030C0000
        PyErr_SetRaisedException(exc);           // steals the reference
#else
        PyErr_Restore(PyObject_Type(exc), exc, PyException_GetTraceback(exc));
#endif
        PyErr_PrintEx(0);   // 0: do not keep it in sys.last_exc (that would keep the plugin's frames -- and open output files -- alive)
    }
    Py_XDECREF(systemExit);
    Py_XDECREF(builtins);
    return cleanExit;
}

// Appends each of `paths` to sys.path unless already there (executePlugin
// runs once per pipeline step; sys.path must not grow with every step).
static void appendSysPaths(const std::vector<std::string>& paths) {
    PyObject* sysPath = PySys_GetObject("path");   // borrowed: own it at once
    if (!sysPath) return;
    Py_INCREF(sysPath);   // code run below (.pth, __eq__) could replace sys.path
    for (size_t i = 0; i < paths.size(); ++i) {
        PyObject* item = pyPath(paths[i]);
        if (item && PySequence_Contains(sysPath, item) == 0) PyList_Append(sysPath, item);
        if (PyErr_Occurred()) reportPythonError("(sys.path setup)");   // never exits on SystemExit
        Py_XDECREF(item);
    }
    Py_DECREF(sysPath);
}

// Imports a plugin from the file found in the plugin path, under its usual
// module name ("FooPlugin"), so the plugin that runs is that file -- not a
// same-named FooPlugin.py earlier on sys.path (the cwd, another plugin
// directory).  Its directory is only *appended* to sys.path, as PluMA always
// did, so the standard library and site-packages win over same-named helper
// files (a csv.py next to a plugin never replaces the real csv module).
// A module already loaded from the same file -- by PluMA or by another
// plugin's plain `import FooPlugin`, whatever the spelling of its path -- is
// reused: plugins are imported once per run, as before.
static const char* const pluginLoaderSource =
    "def _same_file(a, b):\n"
    "    import os\n"
    "    try:\n"
    "        return a is not None and os.path.samefile(a, b)\n"
    "    except (OSError, TypeError, ValueError):\n"
    "        return False\n"
    "\n"
    "def _module_lock(name):\n"
    // importlib's own per-module lock, as a plain `import` takes it: another
    // thread importing the same name waits for the module to finish loading
    // (with spec._initializing set, below) instead of getting it half built.
    "    try:\n"
    "        from importlib._bootstrap import _ModuleLockManager\n"
    "        return _ModuleLockManager(name)\n"
    "    except (ImportError, AttributeError):\n"
    "        import contextlib\n"
    "        return contextlib.nullcontext()\n"
    "\n"
    "def load(name, path):\n"
    "    import sys, importlib.util\n"
    "    with _module_lock(name):\n"
    "        previous = sys.modules.get(name)\n"
    "        if previous is not None and _same_file(getattr(previous, '__file__', None), path):\n"
    "            return previous\n"
    "        spec = importlib.util.spec_from_file_location(name, path)\n"
    "        if spec is None:\n"
    "            raise ImportError('cannot load %s from %s' % (name, path))\n"
    "        m = importlib.util.module_from_spec(spec)\n"
    "        spec._initializing = True\n"
    "        sys.modules[name] = m\n"
    "        try:\n"
    "            spec.loader.exec_module(m)\n"
    "        except BaseException:\n"
    "            if sys.modules.get(name) is m:\n"   // put back what was there
    "                if previous is not None:\n"
    "                    sys.modules[name] = previous\n"
    "                else:\n"
    "                    del sys.modules[name]\n"
    "            raise\n"
    "        finally:\n"
    "            spec._initializing = False\n"
    "        return m\n";

// Per-plugin helper modules.  Plugin directories are on sys.path, so a
// plugin's `import utils` used to share sys.modules['utils'] with every other
// plugin that has a utils.py -- whichever was imported first was used by all.
// This import hook gives each plugin its own copy of a single-file helper
// module that one of its own plugin directories provides, kept in
// sys.modules under a per-plugin key.  The first plugin to load a helper of
// a given name also has it under that plain name (its __name__, and
// sys.modules[name]), so pickling -- e.g. to multiprocessing workers --
// refers to it as before; another plugin's same-named helper is named by its
// key, which pickling resolves through sys.modules (in this process and in
// forked workers; spawned workers import modules by name, so there only the
// first one's objects can be sent).  Names the
// rest of sys.path provides (standard library, site-packages, the current
// directory) still win, as always; helper packages, and helpers found only in
// another plugin's directory, are imported as before (shared).  GIL held.
static const char* const helperIsolationSource = R"PY(
import builtins, importlib.machinery, importlib.util, os, sys

_original_import = builtins.__import__
_dir_plugin = {}    # normalized plugin directory -> plugin name
_plugin_dirs = {}   # plugin name -> its directories, in search order
_resolved = {}      # (plugin, name) -> (sys.path then, (per-plugin key, file) or None)

def _norm(path):
    return os.path.normcase(os.path.normpath(os.path.abspath(path)))

def register(plugin, dirs):
    known = _plugin_dirs.setdefault(plugin, [])
    added = False
    for d in dirs:
        n = _norm(d)
        if n not in known:
            known.append(n)
            _dir_plugin[n] = plugin
            added = True
    if added:
        # Other kitties' imports may add entries meanwhile: iterate over a
        # snapshot (list(dict) is atomic), and tolerate keys gone since.
        for key in [k for k in list(_resolved) if k[0] == plugin]:
            _resolved.pop(key, None)
        _file_plugin.clear()

_file_plugin = {}   # module __file__ -> plugin name or None (cached: imports are frequent)

def _plugin_of(module_globals):
    f = module_globals.get('__file__')
    if not isinstance(f, str):
        return None
    try:
        return _file_plugin[f]
    except KeyError:
        plugin = _file_plugin[f] = _dir_plugin.get(_norm(os.path.dirname(f)))
        return plugin

# Whether directory `d` has the file `filename`, spelled exactly so: a plain
# import matches case even where the file system does not (Windows).
def _has_file(d, filename):
    if not os.path.isfile(os.path.join(d, filename)):
        return False
    if os.name != 'nt':
        return True
    try:
        return filename in os.listdir(d)
    except OSError:
        return False

# Whether a plain import would take something else than <name>.py from
# directory `d`: a package <name>/, or an extension module, comes first there.
def _shadowed_in(d, name):
    if os.path.isfile(os.path.join(d, name, '__init__.py')):
        return True
    return any(_has_file(d, name + suffix) for suffix in importlib.machinery.EXTENSION_SUFFIXES)

def _helper(plugin, name):
    key = (plugin, name)
    cached = _resolved.get(key)
    # (Answered again if sys.path changed since: a module of that name may
    # have become importable elsewhere.)
    if cached is not None and cached[0] == sys.path:
        return cached[1]
    found = None
    if name not in sys.builtin_module_names and name not in getattr(sys, 'stdlib_module_names', ()):
        for d in list(_plugin_dirs.get(plugin, ())):
            if _shadowed_in(d, name):
                break   # (the plain import finds that first)
            path = os.path.join(d, name + '.py')
            if _has_file(d, name + '.py'):
                others = [p for p in sys.path
                          if isinstance(p, str) and _norm(p or '.') not in _dir_plugin]
                # A folder of that name elsewhere is only a namespace package
                # portion (no loader/origin): a plain import prefers a module
                # to it anywhere on sys.path, so it does not win either.
                spec = importlib.machinery.PathFinder.find_spec(name, others)
                if spec is None or spec.loader is None or spec.origin is None:
                    found = ('_pluma_helper__%s__%s' % (plugin, name), path)
                break
    _resolved[key] = (list(sys.path), found)
    return found

def _loader():
    # The plugin loader's module (created just before this one, in the same
    # interpreter): its importlib lock and same-file test are shared.
    return sys.modules['_pluma_plugin_loader']

_DeadlockError = getattr(importlib._bootstrap, '_DeadlockError', ())

def _ready(module, *locks):
    # A module another thread is still executing (spec._initializing, as the
    # plugin loader and this one mark it): wait for it under its import
    # lock(s), as a plain import does -- re-entrant, so a circular import on
    # the same thread gets it at once.
    spec = getattr(module, '__spec__', None)
    if spec is not None and getattr(spec, '_initializing', False):
        for lock in locks:
            try:
                with _loader()._module_lock(lock):
                    pass
            except _DeadlockError:
                # Two threads importing each other's modules (a circular
                # import): the module as it is so far, as a plain import gives.
                pass
    return module

def _load(key, name, path):
    module = sys.modules.get(key)
    if module is not None:
        return _ready(module, key)
    # Already loaded from this very file under its plain name -- the plugin's
    # own module (PluMA loads FooPlugin.py as FooPlugin; a helper may import
    # it back), or this plugin's helper claimed that name: that module, not
    # a second copy.
    module = sys.modules.get(name)
    if module is not None and _loader()._same_file(getattr(module, '__file__', None), path):
        return _ready(module, name, key)
    import contextlib
    with contextlib.ExitStack() as locks:
        locks.enter_context(_loader()._module_lock(key))
        module = sys.modules.get(key)
        if module is not None:
            return module
        # Claiming the plain name too: also under that name's import lock --
        # a plain `import <name>` elsewhere (another plugin without such a
        # helper) waits on it for a module still loading, as for any import.
        claim = name not in sys.modules
        if claim:
            locks.enter_context(_loader()._module_lock(name))
            claim = name not in sys.modules   # (taken meanwhile?)
        _helper_files[key] = path
        spec = importlib.util.spec_from_file_location(name if claim else key, path)
        module = importlib.util.module_from_spec(spec)
        # Marked loading before anyone can see it in sys.modules (see _ready).
        spec._initializing = True
        if claim and sys.modules.setdefault(name, module) is not module:
            # (Cannot happen under the name's lock, but never take over a name.)
            spec = importlib.util.spec_from_file_location(key, path)
            module = importlib.util.module_from_spec(spec)
            spec._initializing = True
        sys.modules[key] = module
        try:
            spec.loader.exec_module(module)
        except BaseException:
            for k in (key, name):
                if sys.modules.get(k) is module:
                    del sys.modules[k]
            raise
        finally:
            spec._initializing = False
        return module

# importlib.reload() of a helper loaded under its private name looks that
# name up again: answered here, as no path entry has such a module.
_helper_files = {}   # private name -> file

class _HelperFinder:
    @staticmethod
    def find_spec(name, path=None, target=None):
        file = _helper_files.get(name)
        return importlib.util.spec_from_file_location(name, file) if file else None

sys.meta_path.append(_HelperFinder)

# The helper `name` of the plugin whose module has these globals, loaded;
# None if there is no such plugin or helper (the normal import then applies).
def _resolve(name, caller):
    plugin = _plugin_of(caller) if caller else None
    if plugin is None:
        return None
    helper = _helper(plugin, name)
    if helper is None:
        return None
    return _load(helper[0], name, helper[1])

def _import(name, globals=None, locals=None, fromlist=(), level=0):
    if level == 0 and globals and name and '.' not in name:
        module = _resolve(name, globals)
        if module is not None:
            return module
    return _original_import(name, globals, locals, fromlist, level)

builtins.__import__ = _import

# importlib.import_module() does not go through __import__: the same choice
# for it, by the calling module (its frame's globals -- import_module has no
# others to go by).
_original_import_module = importlib.import_module

def _import_module(name, package=None):
    if isinstance(name, str) and name and '.' not in name:
        try:
            caller = sys._getframe(1).f_globals
        except (AttributeError, ValueError):
            caller = None
        module = _resolve(name, caller)
        if module is not None:
            return module
    return _original_import_module(name, package)

importlib.import_module = _import_module
)PY";
static PyObject* pyRegisterHelpers = NULL;   // _pluma_helpers.register; like pyLoader

// The loader function, created once per interpreter while it is being set up
// (configureSysPath, before any plugin runs); dropped (pyLoader = NULL) when
// PluMA finalizes Python, so a restarted interpreter gets its own.  If that
// failed, importPluginFile() retries -- possibly on several kitties at once
// (executing the module code can switch threads), so the first loader
// published wins and later ones are discarded.  GIL held.
static PyObject* pyLoader = NULL;

// Guards pyLoader and pyRegisterHelpers: under the GIL alone their
// check-then-store is atomic, but free-threaded builds have no GIL.  Waited
// for without holding the GIL (its holder may be running Python code, which
// needs the GIL on GIL builds).  GIL held on entry and exit.
static std::mutex& loaderMutex = *new std::mutex;   // never destroyed (exit())
struct LoaderLock {
    LoaderLock() {
        if (loaderMutex.try_lock()) return;
        PyThreadState* state = PyEval_SaveThread();
        loaderMutex.lock();
        PyEval_RestoreThread(state);
    }
    ~LoaderLock() { loaderMutex.unlock(); }
    LoaderLock(const LoaderLock&) = delete;
    LoaderLock& operator=(const LoaderLock&) = delete;
};

static void createPluginLoaderLocked() {   // loaderMutex held
    if (pyLoader) return;
    PyObject* code = Py_CompileString(pluginLoaderSource, "<pluma plugin loader>", Py_file_input);
    PyObject* module = code ? PyImport_ExecCodeModule("_pluma_plugin_loader", code) : NULL;
    PyObject* loader = module ? PyObject_GetAttrString(module, "load") : NULL;
    Py_XDECREF(module);
    Py_XDECREF(code);
    pyLoader = loader;   // kept until finalization
    if (pyLoader && !pyRegisterHelpers) {   // (its _load uses the loader module's lock)
        PyObject* helperCode = Py_CompileString(helperIsolationSource, "<pluma helper modules>", Py_file_input);
        PyObject* helpers = helperCode ? PyImport_ExecCodeModule("_pluma_helpers", helperCode) : NULL;
        PyObject* registerHelpers = helpers ? PyObject_GetAttrString(helpers, "register") : NULL;
        Py_XDECREF(helpers);
        Py_XDECREF(helperCode);
        if (!registerHelpers) reportPythonError("(helper module setup)");
        pyRegisterHelpers = registerHelpers;
    }
}

// Whether the loader exists (created if not yet).
static bool createPluginLoader() {
    LoaderLock lock;
    createPluginLoaderLocked();
    return pyLoader != NULL;
}

// New references to the loader and the helper registration (NULL: not
// available), the loader created if not yet (e.g. its creation failed at
// setup).  GIL held.
static void currentLoaders(PyObject*& loader, PyObject*& registerHelpers) {
    LoaderLock lock;
    createPluginLoaderLocked();
    loader = pyLoader;
    registerHelpers = pyRegisterHelpers;
    Py_XINCREF(loader);
    Py_XINCREF(registerHelpers);
}

// New reference to the module, or NULL with a Python error set.  Requires
// the GIL and the plugin's import lock (pluginImportLock).
static PyObject* importPluginFile(const std::string& name, const std::string& path) {
    PyObject* loader = NULL;
    PyObject* registerHelpers = NULL;
    currentLoaders(loader, registerHelpers);
    Py_XDECREF(registerHelpers);
    if (!loader) return NULL;
    PyObject* file = pyPath(path);
    if (!file) { Py_DECREF(loader); return NULL; }
    PyObject* result = PyObject_CallFunction(loader, "sO", name.c_str(), file);
    Py_DECREF(file);
    Py_DECREF(loader);
    return result;
}

// "X.Y" recorded in <venv>/pyvenv.cfg ("version = 3.15.2" or, on newer
// Pythons, "version_info = 3.15.2.final.0"); "" if unreadable.
// A setting of the venv's pyvenv.cfg ("" if absent); `other` is an alternative key.
static std::string venvSetting(const std::string& venv, const std::string& wanted, const std::string& other = "") {
    std::ifstream cfg((venv + "/pyvenv.cfg").c_str());
    std::string line;
    while (std::getline(cfg, line)) {
        std::string::size_type eq = line.find('=');
        if (eq == std::string::npos || eq == 0) continue;
        std::string key = line.substr(0, eq);
        key.erase(key.find_last_not_of(" \t") + 1);
        if (key != wanted && (other.empty() || key != other)) continue;
        std::string::size_type start = line.find_first_not_of(" \t", eq + 1);
        if (start == std::string::npos) return "";
        std::string value = line.substr(start);
        value.erase(value.find_last_not_of(" \t\r") + 1);   // CRLF files: "3.14\r"
        return value;
    }
    return "";
}

static std::string venvPythonVersion(const std::string& venv) {
    const std::string value = venvSetting(venv, "version", "version_info");
    std::string::size_type dot1 = value.find('.');
    std::string::size_type dot2 = dot1 == std::string::npos ? dot1 : value.find('.', dot1 + 1);
    return value.substr(0, dot2);
}

#ifdef _WIN32
// Whether the venv was made by a free-threaded Python.  Its site-packages
// path does not say on Windows (POSIX: lib/pythonX.Yt/): by the interpreter
// that made it (python3.14t.exe), or, for an installation whose python.exe is
// the free-threaded one, by the only runtime DLL its home has.
static bool venvIsFreeThreaded(const std::string& venv, const std::string& version) {
    std::string exe = pluma::toLowerAscii(pluma::baseName(pluma::normalizeSlashes(venvSetting(venv, "executable"))));
    const std::string::size_type dot = exe.rfind(".exe");
    if (dot != std::string::npos) exe.erase(dot);
    if (!exe.empty() && exe[exe.size() - 1] == 't') return true;
    std::string digits = version;
    digits.erase(std::remove(digits.begin(), digits.end(), '.'), digits.end());
    const std::string home = pluma::normalizeSlashes(venvSetting(venv, "home"));
    return !home.empty() && !pluma::fileExists(home + "/python" + digits + ".dll") &&
           pluma::fileExists(home + "/python" + digits + "t.dll");
}
#endif

// Adds the shared plugin venv (.venv, created by resolve_requirements.py)
// to sys.path -- unless pyvenv.cfg says it was built for a different X.Y, in
// which case its compiled extension modules would fail to import.  (A venv
// without a recorded version is used, as before: on POSIX its site-packages
// path is versioned anyway.)  Returns whether the venv was activated.
static bool activateVenv(const std::string& cwd) {
    const std::string venv = cwd + "/.venv";
    if (!pluma::isDirectory(venv)) return false;
    const std::string want = pythonVersion();
    const std::string have = venvPythonVersion(venv);
    if (!have.empty() && have != want) {
        PluginManager::getInstance().log("Ignoring " + venv + ": built for Python " + have +
                                         ", but PluMA embeds Python " + want + ".");
        return false;
    }
#ifdef _WIN32
#ifdef Py_GIL_DISABLED
    const bool freeThreadedBuild = true;
#else
    const bool freeThreadedBuild = false;
#endif
    if (venvIsFreeThreaded(venv, want) != freeThreadedBuild) {
        PluginManager::getInstance().log("Ignoring " + venv + ": made by the " +
                                         (freeThreadedBuild ? "regular" : "free-threaded") + " build of Python " + want +
                                         ", whose extension modules PluMA's Python cannot import.");
        return false;
    }
#endif

    // POSIX venvs keep packages in lib/pythonX.Y[t]/site-packages ("t" for
    // free-threaded builds), Windows venvs in Lib/site-packages.
#ifdef _WIN32
    std::string sitePkgs = venv + "/Lib/site-packages";
#else
#ifdef Py_GIL_DISABLED
    std::string sitePkgs = venv + "/lib/python" + want + "t/site-packages";
#else
    std::string sitePkgs = venv + "/lib/python" + want + "/site-packages";
#endif
#endif
    if (!pluma::isDirectory(sitePkgs))
        return false;

    PyObject* site = PyImport_ImportModule("site");
    PyObject* dir = pyPath(sitePkgs);
    PyObject* result = (site && dir) ? PyObject_CallMethod(site, "addsitedir", "O", dir) : NULL;
    if (!result) reportPythonError("(venv activation)");   // e.g. a .pth calling sys.exit()
    const bool activated = result != NULL;
    Py_XDECREF(result);
    Py_XDECREF(dir);
    Py_XDECREF(site);
    return activated;
}

// Interpreter lifetime.  Python is started lazily, the first time a Python
// plugin (or languageLoad("Python")) needs it -- so pipelines without Python
// steps never load or initialize it -- with Py_InitializeEx(0), which installs
// no SIGINT handler (Ctrl-C keeps ending PluMA); SIGPIPE/SIGXFSZ are then
// ignored, as Py_Initialize() did in earlier versions (setupInterpreter).
//
// Which thread initializes it matters: Py_Finalize must run on that thread,
// that thread must still be alive (otherwise finalization hangs), and it
// becomes Python's "main thread" (signal.signal() works only there).
//   * First needed on PluMA's main thread (every sequential pipeline):
//     initialize right there, as PluMA always did; main() finalizes it.
//   * First needed on a parallel "Kitty" thread, which is short-lived:
//     initialize on a dedicated owner thread that lives until Py::unload().
// Afterwards the GIL is released; every plugin call takes it with
// PyGILState_Ensure/Release (GilGuard), so any thread may run Python plugins.
// Native plugins that use the Python C API themselves must do the same.
static const std::string plumaStartDirectory = pluma::currentDirectory();   // before any plugin runs
// Never destroyed: a plugin may end the process with exit() while the owner
// thread is still waiting on them, and static destructors would pull them out
// from under it.
static std::mutex& pyMutex = *new std::mutex;
static std::condition_variable& pyCv = *new std::condition_variable;
// One lock per plugin module: two kitties running the same plugin do not
// both execute its module, while different plugins import concurrently (a
// slow or blocking import holds up only its own plugin).  Always taken
// *before* the GIL, so a thread waiting for it never holds the GIL.  Never
// destroyed (exit()).
static std::mutex& pyImportLocksMutex = *new std::mutex;   // guards the map only
static std::map<std::string, std::mutex*>& pyImportLocks = *new std::map<std::string, std::mutex*>;

static std::mutex& pluginImportLock(const std::string& module) {
    std::lock_guard<std::mutex> lock(pyImportLocksMutex);
    std::mutex*& m = pyImportLocks[module];
    if (!m) m = new std::mutex;
    return *m;
}
static bool pyReady = false;        // all guarded by pyMutex
static bool pyStarting = false;     // owner thread launched, not yet ready
static bool pyStopping = false;     // unload in progress (pyMutex released while joining)
// PluMA finalized Python at least once (languageUnload).  A later Python
// step starts it again, as PluMA always did; a restart is logged because
// some C extension modules (numpy, ...) do not support being imported again
// in a re-initialized interpreter.
static bool pyShutDown = false;
static bool pyStop = false;
// True on a thread that is inside interpreter startup/shutdown.  Python code
// run there (.pth files, atexit handlers) may call PyPluMA.languageLoad/
// languageUnload, which must not re-enter (pyMutex is held: deadlock).
static thread_local bool inPyLifecycle = false;
static bool pyOwned = false;        // false if someone else initialized Python
static int pyRunning = 0;           // Python plugins currently executing
static PyThreadState* pyMainState = NULL;   // set when initialized on the main thread
// Heap-allocated on purpose: a joinable std::thread with static storage would
// call std::terminate if a plugin ends the process with exit().
static std::thread* pyOwner = NULL;

// Marks the calling thread as inside interpreter startup/configuration for
// its lifetime (restoring the previous value, so it nests).
struct InPyLifecycle {
    bool previous;
    InPyLifecycle() : previous(inPyLifecycle) { inPyLifecycle = true; }
    ~InPyLifecycle() { inPyLifecycle = previous; }
};

#ifdef Py_GIL_DISABLED
#define PLUMA_PYTHON_EXE_NAMES "['python%d.%dt.exe' % _sys.version_info[:2], 'python.exe']"
#else
#define PLUMA_PYTHON_EXE_NAMES "['python.exe']"
#endif

// Whether `obj` has a callable attribute `name` (an instance variable that
// happens to be called output is not a phase).  GIL held.
static bool hasMethod(PyObject* obj, const char* name) {
    PyObject* attribute = PyObject_GetAttrString(obj, name);
    if (!attribute) {
        PyErr_Clear();
        return false;
    }
    const bool callable = PyCallable_Check(attribute) != 0;
    Py_DECREF(attribute);
    return callable;
}

// sys.path for plugins: cwd (PyPluMA lives there), the shared .venv and the
// plugin roots.  Requires the GIL.
static void configureSysPath(const std::string& pluginpath) {
    InPyLifecycle lifecycle;   // .pth files run here may call back into PluMA
#ifdef _WIN32
    // An embedded interpreter reports the host executable (pluma.exe) as
    // sys.executable, so multiprocessing's spawn -- the only start method on
    // Windows -- and subprocess.run([sys.executable, ...]) would relaunch
    // PluMA.  Point them at the python.exe of the embedded installation -- for
    // a free-threaded build its python3.Xt.exe, where there is one: a
    // python.org installation's python.exe beside it is the GIL build, which
    // cannot import free-threaded extension modules.
    if (PyRun_SimpleString(
            "import os as _os, sys as _sys\n"
            "_names = " PLUMA_PYTHON_EXE_NAMES "\n"
            "for _name in _names:\n"
            "    _exe = _os.path.join(_sys.base_exec_prefix, _name)\n"
            "    if _os.path.isfile(_exe):\n"
            "        _sys.executable = _sys._base_executable = _exe\n"
            "        break\n"
            "del _os, _sys, _names, _name, _exe\n") != 0)
        PluginManager::getInstance().log("Could not set sys.executable for the embedded Python.");
#endif
    // The directory PluMA started in (where PyPluMA and the shared .venv
    // live), not the current one: Python starts at the first Python step, and
    // an earlier plugin may have changed directory (chdir/setwd) by then.
    const std::string& cwd = plumaStartDirectory;
    appendSysPaths(std::vector<std::string>(1, cwd + "/"));
    const bool venvActive = activateVenv(cwd);
#ifdef _WIN32
    // With the shared .venv active, child interpreters must see its packages
    // too: sys.executable is the venv's python.exe, and _base_executable stays
    // the installation's -- the layout of a real venv, which multiprocessing's
    // spawn handles (it starts the base python as that venv).
    // Native separators: multiprocessing hands this to its workers as
    // __PYVENV_LAUNCHER__, and the interpreter's own path calculation does
    // not find the venv from a forward-slash path (site.py then warns
    // "Unexpected value in sys.prefix").
    const std::string venvPython = pluma::nativeSlashes(cwd + "/.venv/Scripts/python.exe");
    if (venvActive && pluma::fileExists(venvPython)) {
        PyObject* exe = pyPath(venvPython);
        if (!exe || PySys_SetObject("executable", exe) != 0) PyErr_Clear();
        Py_XDECREF(exe);
    }
#else
    (void) venvActive;
#endif
    std::vector<std::string> roots = pluma::splitPluginPath(pluginpath);
    // One trailing separator ("<cwd>/plugins/" already has it): the same
    // directory must not appear spelled two ways.
    for (size_t i = 0; i < roots.size(); ++i)
        if (!roots[i].empty() && roots[i][roots[i].size() - 1] != '/') roots[i] += "/";
    appendSysPaths(roots);
    // Created here, while the interpreter is being set up and no plugin runs
    // yet, so plugins importing concurrently (per-module locks) never race
    // to create it.
    if (!createPluginLoader()) reportPythonError("(plugin loader setup)");
}

static void setupInterpreter(const std::string& pluginpath) {
    // site.py runs .pth files during Py_InitializeEx; one calling
    // PyPluMA.languageLoad/languageUnload must not re-enter (pyMutex is held).
    InPyLifecycle lifecycle;
    Py_InitializeEx(0);
#ifndef _WIN32
    // What Py_Initialize() -- used by earlier versions, also on the first
    // Python step -- does besides installing a SIGINT handler: ignore SIGPIPE
    // and SIGXFSZ, so writes to a closed pipe raise BrokenPipeError rather
    // than killing PluMA.  (Python's subprocess restores them in children.)
    std::signal(SIGPIPE, SIG_IGN);
    std::signal(SIGXFSZ, SIG_IGN);
#endif
    configureSysPath(pluginpath);
}

// Set by Py::unloadAtExit(): the end-of-run shutdown.
static std::atomic<bool> unloadingAtExit(false);

// GIL held.  Whether a non-daemon Python thread other than the calling one
// (and Python's main thread), or a non-daemon multiprocessing child, is still
// running: Py_FinalizeEx joins those (the children through multiprocessing's
// atexit handler), so one that never ends -- a server, a watcher a plugin
// started -- would hang PluMA at exit.  (Modules not imported: none.)
static bool nonDaemonThreadsRunning() {
    PyObject* globals = PyDict_New();
    if (!globals) { PyErr_Clear(); return false; }
    PyDict_SetItemString(globals, "__builtins__", PyEval_GetBuiltins());
    PyObject* result = PyRun_String(
        "import sys\n"
        "_t = sys.modules.get('threading')\n"
        "_n = 0 if _t is None else sum(1 for _x in _t.enumerate()\n"
        "    if _x.is_alive() and not _x.daemon and _x.ident != _t.get_ident() and _x is not _t.main_thread())\n"
        "_m = sys.modules.get('multiprocessing.process')\n"
        "if _m is not None:\n"
        "    try:\n"
        "        _n += sum(1 for _p in _m.active_children() if not _p.daemon)\n"
        "    except Exception:\n"
        "        pass\n",
        Py_file_input, globals, globals);
    bool running = false;
    if (result) {
        PyObject* n = PyDict_GetItemString(globals, "_n");   // borrowed
        running = n && PyLong_AsLong(n) > 0;
        Py_DECREF(result);
    }
    if (PyErr_Occurred()) PyErr_Clear();
    Py_DECREF(globals);
    return running;
}

// GIL held.  Finalizes the interpreter -- or, at the end of the run with
// non-daemon threads still running, only flushes Python's output and leaves
// it (the process ends right after, as in earlier versions).
// Bumped whenever PluMA finalizes an interpreter: thread states saved
// before (foreignMainState) are gone with it.
static std::atomic<unsigned> pyGeneration(0);

static void finalizeInterpreter() {
    if (unloadingAtExit && nonDaemonThreadsRunning()) {
        flushPythonStreams();
        PluginManager::getInstance().log("Python threads or processes started by plugins are still running; not "
                                         "finalizing Python at exit (output flushed).");
        // Give the GIL back: later shutdown code (another language's exit
        // finalizers calling into Python, e.g. reticulate) must still get it.
        PyEval_SaveThread();
        return;
    }
    {
        LoaderLock lock;
        Py_CLEAR(pyLoader);
        Py_CLEAR(pyRegisterHelpers);
    }
    inPyLifecycle = true;
    ++pyGeneration;
    Py_FinalizeEx();   // flushes output, runs atexit handlers
    inPyLifecycle = false;
}

static void pythonOwnerThread(std::string pluginpath) {
    setupInterpreter(pluginpath);
    PyThreadState* state = PyEval_SaveThread();   // release the GIL
    {
        std::unique_lock<std::mutex> lock(pyMutex);
        pyReady = true;
        pyCv.notify_all();
        pyCv.wait(lock, [] { return pyStop; });
    }
    PyEval_RestoreThread(state);
    finalizeInterpreter();
}

