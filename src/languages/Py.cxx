static bool pythonInProcess();   // defined below

enum PythonAvailability { PYTHON_OK, PYTHON_NOT_FOUND, PYTHON_SHUTTING_DOWN, PYTHON_START_FAILED };

// Starts Python if needed.  With `run`, also counts the caller as a running
// plugin (until releasePython()), so the interpreter cannot be unloaded under
// it.
static PythonAvailability acquirePython(const std::string& pluginpath, bool run) {
    std::unique_lock<std::mutex> lock(pyMutex);
    // Another thread is starting Python: wait for it (pyCv.wait releases
    // pyMutex, so callers can arrive mid-startup) -- also for languageLoad,
    // whose caller may use the interpreter right after it returns.  (Startup
    // code -- .pth files, sitecustomize -- therefore must not wait for a
    // thread of its own that calls PyPluMA: that thread waits for startup.)
    // The caller may hold the GIL -- e.g. a native plugin that started Python
    // itself and then calls languageLoad("Python") -- while the thread doing
    // the start (adopting that interpreter) waits for exactly that GIL: give
    // it up while waiting, as Py_BEGIN_ALLOW_THREADS would.  Re-taken without
    // pyMutex held (the GIL is never awaited with pyMutex held).
    for (;;) {
        while (pyStarting) {
            PyThreadState* saved = NULL;
            if (pythonInProcess() && threadHoldsGil()) {
                lock.unlock();
                saved = PyEval_SaveThread();
                lock.lock();
            }
            pyCv.wait(lock, [] { return !pyStarting; });
            if (saved) {
                lock.unlock();
                PyEval_RestoreThread(saved);
                lock.lock();
            }
        }
        if (!pyStopping) break;
        // Being shut down (languageUnload on another thread).  A thread of
        // Python's own -- one with a thread state, e.g. a non-daemon Python
        // thread calling back into PluMA -- must not wait: finalization may be
        // waiting for it.  Any other caller (a step on a kitty) waits for the
        // shutdown to end and then starts Python again, instead of failing
        // only because of when it happened to start.
        if (pythonInProcess() && PyGILState_GetThisThreadState() != NULL) return PYTHON_SHUTTING_DOWN;
        pyCv.wait(lock, [] { return !pyStopping; });
    }
    if (!pyReady) {
        if (pyShutDown)
            PluginManager::getInstance().log("Restarting Python after languageUnload(\"Python\"); C extension "
                                             "modules that cannot be re-initialized (e.g. numpy) may fail to import.");
#ifdef _WIN32
        if (!pythonDllLoaded()) return PYTHON_NOT_FOUND;
#endif
        if (Py_IsInitialized()) {
            // Started by someone else (e.g. a native plugin): use it, but still
            // give plugins PluMA's sys.path.  (If that code keeps the GIL on
            // another thread, this waits for it -- its responsibility.)  The
            // GIL is never awaited with pyMutex held: whoever holds the GIL
            // may need pyMutex (languageLoad/Unload).  pyStarting keeps other
            // callers waiting meanwhile, as for an owner-thread start.
            pyStarting = true;
            lock.unlock();
            PyGILState_STATE gil = PyGILState_Ensure();
            configureSysPath(pluginpath);
            PyGILState_Release(gil);
            lock.lock();
            pyStarting = false;
            pyReady = true;
            pyCv.notify_all();
        } else if (PluginManager::isMainThread()) {
            // Not under pyMutex: startup runs site/.pth/sitecustomize code,
            // which may start threads that call back into PluMA (they see
            // pyStarting).  Other callers wait for the start meanwhile.
            pyStarting = true;
            lock.unlock();
            setupInterpreter(pluginpath);
            PyThreadState* mainState = PyEval_SaveThread();   // release the GIL
            lock.lock();
            pyMainState = mainState;
            pyStarting = false;
            pyOwned = true;
            pyReady = true;
            pyCv.notify_all();
        } else {
            try {
                pyOwner = new std::thread(pythonOwnerThread, pluginpath);
            } catch (const std::exception&) {   // out of threads/memory
                // Nothing was started: leave the state as it was, so later
                // steps can try again instead of waiting for a start forever.
                return PYTHON_START_FAILED;
            }
            pyOwned = true;
            pyStop = false;
            pyStarting = true;
            pyCv.wait(lock, [] { return pyReady; });
            pyStarting = false;
            pyCv.notify_all();   // wake callers waiting for the start to finish
        }
    }
    if (run) ++pyRunning;
    return PYTHON_OK;
}

static void releasePython() {
    std::lock_guard<std::mutex> lock(pyMutex);
    --pyRunning;
}

struct GilGuard {
    PyGILState_STATE state;
    GilGuard() : state(PyGILState_Ensure()) {}
    ~GilGuard() { PyGILState_Release(state); }
};
#endif

void Py::executePlugin(
    std::string pluginname,
    std::string inputname,
    std::string outputname
) {
#ifdef HAVE_PYTHON
    // The first plugin directory that holds the plugin (the same rule every
    // other language uses).  Looked up first: a missing plugin needs
    // neither the interpreter started nor the GIL.
    const std::string pluginFile = findPluginFile(pluginname);
    switch (acquirePython(pluginpath, true)) {
    case PYTHON_OK:
        break;
    case PYTHON_SHUTTING_DOWN:
        PluginManager::getInstance().log("Python is being shut down (languageUnload); cannot run " + pluginname + ".");
        throw PluginNotStarted("Python is shutting down");
    case PYTHON_NOT_FOUND:
#ifdef _WIN32
        PluginManager::getInstance().log("Could not locate " + pythonDllName() +
                                         " (not on PATH, in the PEP 514 registry, or in the build-time Python"
                                         " directory); cannot run " + pluginname + ".");
#endif
        throw PluginNotStarted("Python runtime not found");
    case PYTHON_START_FAILED:
        PluginManager::getInstance().log("Could not start a thread for the Python interpreter; cannot run " +
                                         pluginname + ".");
        throw PluginNotStarted("Python could not be started");
    }
    // Declared before `gil` so it is released after the GIL, on every exit
    // path: while counted, Py::unload() will not finalize the interpreter.
    struct Running { ~Running() { releasePython(); } } running;
    std::unique_lock<std::mutex> importLock(pluginImportLock(pluginname + "Plugin"));   // before the GIL; see above
    GilGuard gil;   // released on every exit path, including exceptions
    // Python's sys.stdout/stderr are flushed when the step ends (any exit
    // path; before the GIL is released): redirected output is block-buffered,
    // and a later step may end the process abruptly (abortRun), losing what
    // earlier Python steps printed.
    struct FlushStreams { ~FlushStreams() { flushPythonStreams(); } } flushStreams;
    // Its directories, for the plugin's own helper modules (appended; see
    // importPluginFile): the one its file is in, then <root>/<plugin>/ under
    // every other plugin root, as earlier versions added them -- a helper may
    // live in another root's copy of the plugin directory.  The plugin roots
    // themselves were added at initialization.  Once per plugin and
    // interpreter (pyGeneration): later steps, e.g. a fan-out of kitties
    // running it, skip the file checks and calls.  (Its own mutex: free-
    // threaded builds have no GIL to serialize kitties.)
    static std::mutex& setUpMutex = *new std::mutex;   // never destroyed
    static std::map<std::string, unsigned>& setUp = *new std::map<std::string, unsigned>;
    bool alreadySetUp;
    {
        std::lock_guard<std::mutex> lock(setUpMutex);
        std::map<std::string, unsigned>::const_iterator done = setUp.find(pluginname);
        alreadySetUp = done != setUp.end() && done->second == pyGeneration.load();
    }
    if (!alreadySetUp) {
        std::vector<std::string> dirs(1, pluma::dirName(pluginFile) + "/");
        for (const std::string& root : pluma::splitPluginPath(pluginpath)) {
            if (root.empty()) continue;
            const std::string dir = pluma::joinPath(root, pluginname + "/");   // the spelling findInPluginPath uses
            if (pluma::isDirectory(dir) && dir != pluma::normalizeSlashes(dirs[0]))
                dirs.push_back(dir);
        }
        // Its helper modules first (see helperIsolationSource), and only then
        // sys.path: a directory on sys.path that is not registered yet looks
        // like a shared one to another plugin's import on another kitty, which
        // would cache the wrong answer.  Without them (their setup failed,
        // reported once), not retried every step.
        bool registered = true;
        PyObject* loader = NULL;
        PyObject* registerHelpers = NULL;
        currentLoaders(loader, registerHelpers);
        Py_XDECREF(loader);
        // (A loader that could not be created leaves its error pending: the
        // import below tries again and reports it there, as an import error.)
        if (!registerHelpers) PyErr_Clear();
        if (registerHelpers) {
            PyObject* list = PyList_New(0);
            for (size_t i = 0; list && i < dirs.size(); ++i) {
                PyObject* item = pyPath(dirs[i]);
                if (item) PyList_Append(list, item);
                Py_XDECREF(item);
            }
            PyObject* name = PyUnicode_FromString(pluginname.c_str());
            PyObject* result = (list && name) ? PyObject_CallFunctionObjArgs(registerHelpers, name, list, NULL) : NULL;
            if (!result) {
                reportPythonError("(helper module setup)");
                registered = false;   // retried next step
            }
            Py_XDECREF(result);
            Py_XDECREF(name);
            Py_XDECREF(list);
        }
        Py_XDECREF(registerHelpers);
        appendSysPaths(dirs);
        if (registered) {
            std::lock_guard<std::mutex> lock(setUpMutex);
            setUp[pluginname] = pyGeneration.load();
        }
    }

    const std::string className = pluginname + "Plugin";
    PyObject* module = NULL;
    PyObject* cls = NULL;
    PyObject* plugin = NULL;
    bool exitedCleanly = false;   // sys.exit()/sys.exit(0): remaining phases skipped

    // A Python error in `phase`: print it, then either accept a clean
    // sys.exit(0) or release references and abort this plugin.  Failures
    // before input() (import, construction) are PluginNotStarted: the plugin
    // never reached a phase that writes its output.
    bool beforeInput = true;
    auto handleError = [&](const std::string& phase) {
        // Classified before printing: an input() that died of an unmet
        // PyPluMA.dependency() never started its work.
        const bool dependencyError = PluginManager::takeDependencyFailed();
        // sys.exit(0) ends the plugin successfully -- but only once it has
        // started (input() onwards).  Exiting during import/construction
        // means it never ran: a failure, not a silently "completed" step.
        if (reportPythonError(pluginname) && !beforeInput) {
            exitedCleanly = true;
            // An unmet dependency() the plugin caught before exiting: keep
            // the mark, so the step still fails (see readConfig).
            if (dependencyError) PluginManager::markDependencyFailed();
            return;
        }
        Py_XDECREF(plugin);
        Py_XDECREF(cls);
        Py_XDECREF(module);
        PluginManager::getInstance().log("Python Plugin "+pluginname+" failed during "+phase+".");
        const std::string msg = "Python plugin " + pluginname + " failed during " + phase;
        // input() raising because of an unmet PyPluMA.dependency(): not started.
        if (beforeInput || (phase == "input" && dependencyError))
            throw PluginNotStarted(msg);
        throw std::runtime_error(msg);
    };

    // Calls plugin.<method>(path) -- or plugin.<method>() when path is NULL --
    // unless an earlier phase already exited cleanly.
    auto callPhase = [&](const char* method, const std::string* path) {
        if (exitedCleanly) return;
        // run()/output() are optional, like the empty defaults of the C++
        // Plugin base class (input() is checked before this point).
        if (!hasMethod(plugin, method)) {
            PluginManager::getInstance().log(std::string("Python Plugin ") + pluginname + " has no " + method + "(); skipped.");
            return;
        }
        PluginManager::getInstance().log(std::string("Executing ") + method + "() For Python Plugin " + pluginname);
        PyObject* result = NULL;
        if (path) {
            PyObject* arg = pyPath(*path);
            if (!arg) { handleError(method); return; }
            result = PyObject_CallMethod(plugin, method, "O", arg);
            Py_DECREF(arg);
        } else {
            result = PyObject_CallMethod(plugin, method, NULL);
        }
        if (!result) { handleError(method); return; }
        Py_DECREF(result);
    };

    module = importPluginFile(className, pluginFile);
    importLock.unlock();   // the plugin's own phases run concurrently
    if (module) cls = PyObject_GetAttrString(module, className.c_str());
    if (cls) plugin = PyObject_CallObject(cls, NULL);
    if (!plugin) handleError(!module ? "import" : !cls ? "class lookup" : "construction");

    // No input() at all: nothing has run yet (same as Java's missing input()).
    if (!hasMethod(plugin, "input")) {
        Py_DECREF(plugin);
        Py_DECREF(cls);
        Py_DECREF(module);
        PluginManager::getInstance().log("Python Plugin "+pluginname+" has no input() method.");
        throw PluginNotStarted("Python plugin " + pluginname + " has no input() method");
    }
    // Paths Python cannot decode: fail before input() runs (not started).
    {
        PyObject* in = pyPath(inputname);
        PyObject* out = in ? pyPath(outputname) : NULL;
        Py_XDECREF(in);
        Py_XDECREF(out);
        if (!in || !out) handleError("path decoding");
    }
    beforeInput = false;
    callPhase("input", &inputname);
    callPhase("run", NULL);
    callPhase("output", &outputname);

    Py_XDECREF(plugin);
    Py_XDECREF(cls);
    Py_XDECREF(module);
    //Py_Finalize();
    PluginManager::getInstance().log("Python Plugin "+pluginname+" completed successfully.");
#else
    notEnabled(pluginname);
#endif
}

#ifdef HAVE_PYTHON
// The GIL held for a C/C++ plugin step on PluMA's main thread (see Py.h).
// While held, the step counts as a running Python user (pyRunning), so no
// other thread can finalize the interpreter under it.
static thread_local bool nativeStep = false;      // inside a C/C++ plugin step
static thread_local bool nativePluginStep = false;   // inside one the import scan did not flag
static thread_local bool nativeGil = false;       // ...and holding the GIL for it
static thread_local PyGILState_STATE nativeGilState;

// Takes the GIL for the current native step, if Python is up.  Never called
// with pyMutex held: whoever holds the GIL may be waiting for pyMutex.
// Always on PluMA's main thread, also while parallel kitties run: in every
// earlier version the main thread held the GIL once Python had started, and
// C/C++ plugins call the C API relying on that -- without it they would
// corrupt the interpreter.  Python steps on kitties wait for such a native
// step meanwhile.  PluMA's own locks are never taken in an order that could
// deadlock with this; but a plugin that waits, while holding it, for work
// that needs the GIL (its own Python worker threads, a Python kitty's
// output) must release it around that wait (Py_BEGIN_ALLOW_THREADS), as in
// earlier versions, whose main thread held it all along (see the README).
static void takeNativeGil() {
    if (!nativeStep || nativeGil || !PluginManager::isMainThread()) return;
    {
        std::lock_guard<std::mutex> lock(pyMutex);
        if (!pyReady || pyStopping || pyStarting) return;
        ++pyRunning;
    }
    nativeGilState = PyGILState_Ensure();
    nativeGil = true;
}

// Gives it back.
static void dropNativeGil() {
    if (!nativeGil) return;
    PyGILState_Release(nativeGilState);
    nativeGil = false;
    releasePython();
}
#endif

std::string Py::runtimeDllName() {
#if defined(HAVE_PYTHON) && defined(_WIN32)
    return pythonDllName();
#else
    return "";
#endif
}

bool Py::preloadRuntime(bool stableAbi) {
#if defined(HAVE_PYTHON) && defined(_WIN32)
    std::lock_guard<std::mutex> lock(pyMutex);
    if (!pythonDllLoaded()) return false;
    if (!stableAbi) return true;
    // python3.dll (the stable ABI, forwarding to pythonXY.dll) ships next to
    // pythonXY.dll: load it from the directory the interpreter came from.
    if (GetModuleHandleA("python3.dll")) return true;
    HMODULE runtime = GetModuleHandleA(pythonDllName().c_str());
    char file[MAX_PATH * 4];
    const DWORD n = runtime ? GetModuleFileNameA(runtime, file, sizeof(file)) : 0;
    if (n == 0 || n >= sizeof(file)) return false;
    std::vector<std::string> dirs(1, pluma::dirName(pluma::normalizeSlashes(file)));
    return pluma::preloadDll("python3.dll", dirs);
#else
    (void) stableAbi;
    return false;
#endif
}

#ifdef HAVE_PYTHON
static void flushPythonStreams() {   // GIL held
    PyObject* error_type, *error_value, *error_tb;
    PyErr_Fetch(&error_type, &error_value, &error_tb);
    const char* names[] = { "stdout", "stderr" };
    for (const char* name : names) {
        PyObject* stream = PySys_GetObject(name);   // borrowed
        // (No Py_None comparison: a data import, which /DELAYLOAD of
        // pythonXY.dll does not allow.  None.flush() just fails, cleared below.)
        if (!stream) continue;
        PyObject* result = PyObject_CallMethod(stream, "flush", NULL);
        if (result) Py_DECREF(result);
        else PyErr_Clear();
    }
    PyErr_Restore(error_type, error_value, error_tb);
}
#endif

void Py::flushPythonBeforeAbort() {
#ifdef HAVE_PYTHON
    {
        // pyMutex is held only briefly (state changes, not while Python
        // runs): wait for it a bounded time rather than giving up at once,
        // so buffered output is not lost to a momentary holder.  Bounded,
        // as the holder may be blocked on this thread.
        std::unique_lock<std::mutex> lock(pyMutex, std::defer_lock);
        if (!pluma::lockBounded(lock, std::chrono::milliseconds(500)) || !pyReady || pyStopping || pyStarting) return;
        // Counted as a running plugin from here on (never uncounted: the
        // process ends right after): a Py::unload() on another thread now
        // refuses to finalize the interpreter under the flush below.
        ++pyRunning;
    }
    // This thread may hold the GIL (e.g. a Python thread).
    // An attached thread state is the signal, not PyGILState_Check(), which
    // returns 1 unconditionally once subinterpreters have disabled GIL-state
    // checking (see Py::unload).
    // It is given up (and not taken back: the process ends right after), so
    // that the flush below can run on a helper thread with a time limit: a
    // stream's flush may block for good (a full pipe nobody reads).
    if (threadHoldsGil()) PyEval_SaveThread();
    // Another thread may hold the GIL and never release it -- e.g. one that
    // is waiting for this thread -- so take it on a helper thread and wait
    // a bounded time; the process ends right after either way.
    pluma::runBounded([] {
        PyGILState_STATE gil = PyGILState_Ensure();
        flushPythonStreams();
        PyGILState_Release(gil);
    }, std::chrono::seconds(2));
#endif
}

#ifdef HAVE_PYTHON
// A native plugin that started Python itself on the main thread
// (Py_Initialize, which leaves the calling thread holding the GIL) keeps
// the GIL there for good.  Earlier versions let it: but a Python plugin on
// a parallel kitty then waits for the GIL forever, while the main thread
// waits for that kitty at LitterGather.  So between steps it is released
// (the thread state kept here), and every later native step on the main
// thread takes it back for its duration -- the plugins of those steps can
// still use the C API as before.  Main thread only.
static PyThreadState* foreignMainState = NULL;
static unsigned foreignMainGeneration = 0;   // pyGeneration when it was saved

// Whether pythonXY.dll is in the process already; never loads it (any
// Python call would, through the delay-load).
static bool pythonInProcess() {
#ifdef _WIN32
    // Once loaded it stays loaded (PluMA never frees it): remembered, as this
    // runs around every native step.
    static std::atomic<bool> loaded(false);
    if (loaded.load()) return true;
    if (GetModuleHandleA(pythonDllName().c_str()) == NULL) return false;
    loaded = true;
    return true;
#else
    return true;
#endif
}
#endif

void* Py::pauseGil() {
#ifdef HAVE_PYTHON
    if (!pythonInProcess() || !threadHoldsGil()) return NULL;
    return PyEval_SaveThread();
#else
    return NULL;
#endif
}

void Py::resumeGil(void* paused) {
#ifdef HAVE_PYTHON
    if (paused) PyEval_RestoreThread(static_cast<PyThreadState*>(paused));
#else
    (void) paused;
#endif
}

void Py::beginNativeStep() {
#ifdef HAVE_PYTHON
    if (!PluginManager::isMainThread()) return;
    nativeStep = true;
    if (foreignMainState) {
        PyThreadState* state = foreignMainState;
        foreignMainState = NULL;
        // Unless that interpreter was finalized since (languageUnload): its
        // thread states were freed with it.
        if (foreignMainGeneration == pyGeneration.load()) {
            PyEval_RestoreThread(state);   // waits for the GIL like takeNativeGil()
            return;
        }
    }
    takeNativeGil();
#endif
}

bool Py::markNativePluginStep(bool begin) {
#ifdef HAVE_PYTHON
    if (!PluginManager::isMainThread()) return false;
    if (begin) {
        nativePluginStep = true;
        return false;
    }
    nativePluginStep = false;
    return nativeStep;   // (set by languageLoad("Python") in it)
#else
    (void) begin;
    return false;
#endif
}

void Py::endNativeStep() {
#ifdef HAVE_PYTHON
    if (!PluginManager::isMainThread()) return;
    dropNativeGil();
    nativeStep = false;
    releaseForeignGil();
#endif
}

bool Py::onMainThread() {
#ifdef HAVE_PYTHON
    return PluginManager::isMainThread();
#else
    return false;
#endif
}

bool Py::foreignGilSaved() {
#ifdef HAVE_PYTHON
    return PluginManager::isMainThread() && foreignMainState != NULL;
#else
    return false;
#endif
}

void Py::releaseForeignGil() {
#ifdef HAVE_PYTHON
    if (!PluginManager::isMainThread() || foreignMainState) return;
    // Still holding the GIL here: it is a plugin's (see foreignMainState).
    if (pythonInProcess() && Py_IsInitialized() && threadHoldsGil()) {
        foreignMainGeneration = pyGeneration.load();
        foreignMainState = PyEval_SaveThread();
    }
#endif
}

void Py::unloadAtExit() {
#ifdef HAVE_PYTHON
    unloadingAtExit = true;
    // A thread a plugin left holding the GIL for good (native code that never
    // releases it) would make the shutdown below wait forever: if the GIL
    // cannot be had in a while, Python is left as it is (the process ends
    // right after, as in earlier versions).  Not if this thread holds it
    // itself (a native step's hold, given back by unload()).
    bool running;
    {
        std::lock_guard<std::mutex> lock(pyMutex);
        running = pyReady && !pyStopping && !pyStarting;
    }
    if (running && !(nativeGil && PluginManager::isMainThread()) && !threadHoldsGil() &&
        !pluma::runBounded([] {
            PyGILState_STATE gil = PyGILState_Ensure();
            PyGILState_Release(gil);
        }, std::chrono::seconds(5))) {
        PluginManager::getInstance().log("Another thread keeps Python's GIL; not shutting Python down at exit.");
        return;
    }
#endif
    unload();
}

void Py::load() {
#ifdef HAVE_PYTHON
    // Failure (runtime not found) is reported when a plugin actually runs.
    if (inPyLifecycle) return;   // from a .pth file / atexit handler: already in progress
    acquirePython(pluginpath, false);
    // languageLoad("Python") from a native plugin on the main thread: like
    // earlier versions, the plugin then holds the GIL for the rest of its step
    // -- also one the import scan did not see use Python (it reaches Python
    // through dlsym, say): asking for Python says it does.
    if (nativePluginStep && !nativeStep && PluginManager::isMainThread()) nativeStep = true;
    takeNativeGil();
#endif
}

void Py::unload() {
#ifdef HAVE_PYTHON
    // Only touch Python if PluMA started it (on Windows any call would
    // otherwise trigger the delay-load of pythonXY.dll), and finalize it on
    // the thread that initialized it.
    if (inPyLifecycle) return;   // from an atexit handler during finalization
    // languageUnload("Python") from a native plugin step that holds the GIL
    // for compatibility (see beginNativeStep): give it back for the checks
    // below -- that hold is PluMA's own, not the plugin's.  Before pyMutex:
    // GIL operations never happen under it (releasing a thread state can run
    // Python code that calls back into PluMA).  It stays counted in
    // pyRunning until the unload really happens (commitDrop); if the unload
    // is refused, the step gets the GIL back (the plugin may go on using the
    // C API after languageLoad("Python")) -- after pyMutex is released, as
    // `lock` below is destroyed first.  (nativeGil is the main thread's.)
    bool nativeReleased = false;
    if (nativeGil && PluginManager::isMainThread()) {
        PyGILState_Release(nativeGilState);
        nativeGil = false;
        nativeReleased = true;
    }
    struct RestoreNativeGil {
        bool& released;
        ~RestoreNativeGil() {
            if (!released) return;
            nativeGilState = PyGILState_Ensure();
            nativeGil = true;
        }
    } restoreNativeGil = { nativeReleased };
    // Mid-run, not while a thread a Python plugin started (a server, a
    // watcher) is still running: Py_FinalizeEx would wait for it for good.
    // (At the end of the run, finalizeInterpreter leaves Python as it is.)
    if (!unloadingAtExit) {
        bool ready;
        {
            std::lock_guard<std::mutex> state(pyMutex);
            ready = pyReady && !pyStopping && !pyStarting;
        }
        if (ready) {
            PyGILState_STATE gil = PyGILState_Ensure();
            const bool threadsRunning = nonDaemonThreadsRunning();
            PyGILState_Release(gil);
            if (threadsRunning) {
                PluginManager::getInstance().log("Ignoring languageUnload(\"Python\"): threads or processes started "
                                                 "by Python plugins are still running.");
                return;
            }
        }
    }
    std::unique_lock<std::mutex> lock(pyMutex);
    // The owner thread may already have set pyReady while the thread that
    // launched it has not yet woken up: finalizing now would leave that
    // thread waiting for pyReady forever (and pyStarting stuck).
    if (pyStarting) {
        PluginManager::getInstance().log("Ignoring languageUnload(\"Python\") while Python is starting.");
        return;
    }
    auto commitDrop = [&] {
        if (nativeReleased) {
            --pyRunning;
            nativeReleased = false;
        }
    };
    const int othersRunning = pyRunning - (nativeReleased ? 1 : 0);
    if (pyReady && !pyOwned && !pyStopping && othersRunning == 0 &&
        PluginManager::isMainThread() && Py_IsInitialized()) {
        // Started by someone else (a native plugin) but used by PluMA's Python
        // plugins: finalize it at the end as PluMA always did, so their
        // buffered output is flushed and atexit handlers run.
        // Only if it was started on this thread, though: Py_FinalizeEx must
        // run on the initializing thread.  Py_Initialize leaves that thread a
        // persistent thread state (PluMA's own Ensure/Release pairs do not);
        // without one, Python was started on another thread (e.g. a kitty
        // that has since ended), and finalizing here could hang -- leave it
        // to the end of the process.
        if (!PyGILState_GetThisThreadState()) {
            PluginManager::getInstance().log("Python was started by a native plugin on another thread; "
                                             "not finalizing it at exit.");
            return;
        }
        commitDrop();
        pyReady = false;
        pyStopping = true;
        lock.unlock();
        foreignMainState = NULL;   // re-attached by the Ensure below; gone after finalizing
        PyGILState_Ensure();   // reentrant if this thread already holds it
        finalizeInterpreter();
        inPyLifecycle = false;
        lock.lock();
        pyStopping = false;
        pyShutDown = true;
        pyCv.notify_all();   // callers waiting for the shutdown to end (acquirePython)
        return;
    }
    if (!pyReady || !pyOwned || pyStopping) return;
    if (othersRunning > 0) {
        // e.g. PyPluMA.languageUnload("Python") from inside a Python plugin:
        // finalizing under a running plugin would deadlock or crash.
        PluginManager::getInstance().log("Ignoring languageUnload(\"Python\") while a Python plugin is running.");
        return;
    }
    // Not PyGILState_Check(): it returns 1 unconditionally once subinterpreters
    // have disabled GIL-state checking.  An attached thread state is the
    // direct signal that this thread holds the GIL.
    const bool holdsGil = threadHoldsGil();
    // A Python-created thread (threading.Thread) calling PyPluMA.languageUnload
    // does not hold the GIL here -- the SWIG wrapper (-threads) released it --
    // but it still has its own thread state, and Py_FinalizeEx would wait for
    // that very thread (non-daemon threads are joined): deadlock.  The saved
    // state of the main thread (main-thread mode) is the only exception.
    const PyThreadState* ownState = PyGILState_GetThisThreadState();
    const bool pythonThread = ownState != NULL && ownState != pyMainState;
    if (holdsGil || pythonThread) {
        // The caller holds the GIL (a native plugin inside PyGILState_Ensure)
        // or is a Python thread: finalization needs the GIL itself and would
        // wait for this thread, so it would deadlock.
        PluginManager::getInstance().log("Ignoring languageUnload(\"Python\") from a thread that holds the GIL "
                                         "or belongs to Python; Python is shut down when PluMA exits.");
        return;
    }
    if (pyMainState && !PluginManager::isMainThread()) {
        PluginManager::getInstance().log("Ignoring languageUnload(\"Python\") from a worker thread; "
                                         "Python is shut down when PluMA exits.");
        return;
    }
    // Mark the interpreter unavailable *before* releasing pyMutex, so no other
    // thread acquires it or starts a second unload mid-shutdown.  pyMutex is
    // not held while finalizing: Py_FinalizeEx waits for non-daemon Python
    // threads, which may call back into PluMA (they get "shutting down").
    commitDrop();
    pyReady = false;
    pyStopping = true;
    if (pyMainState) {
        PyThreadState* state = pyMainState;
        pyMainState = NULL;
        lock.unlock();
        PyEval_RestoreThread(state);
        finalizeInterpreter();
        lock.lock();
    } else {
        pyStop = true;
        pyCv.notify_all();
        lock.unlock();      // the owner thread needs pyMutex to wake up
        pyOwner->join();
        lock.lock();
        delete pyOwner;
        pyOwner = NULL;
    }
    pyOwned = false;
    pyStopping = false;
    pyShutDown = true;
    pyCv.notify_all();   // callers waiting for the shutdown to end (acquirePython)
#endif
}
